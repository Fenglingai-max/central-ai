import test from 'node:test';
import assert from 'node:assert/strict';
import { Readable } from 'node:stream';
import { createAuthService } from '../server/auth.js';
import { createApp } from '../server/app.js';

const SERVER = 'https://api.central.example', STATIC = 'https://fenglingai-max.github.io';
const auth = () => createAuthService({ publicOrigin: SERVER, allowedOrigins: [STATIC] });
async function request(app, { method = 'GET', url = '/api/config', origin, body, headers = {} } = {}) {
  const req = Readable.from(body === undefined ? [] : [typeof body === 'string' ? body : JSON.stringify(body)]);
  Object.assign(req, { method, url, socket: { remoteAddress: '127.0.0.1' }, headers: { ...(origin ? { origin } : {}), ...(body === undefined ? {} : { 'content-type': 'application/json' }), ...headers } });
  const result = {};
  const res = { writeHead(status, responseHeaders) { result.status = status; result.headers = responseHeaders; }, end(data) { result.raw = data; if (data) { try { result.body = JSON.parse(data); } catch {} } } };
  await app(req, res);
  return result;
}

test('public readiness/config states are honest and same-origin runtime config is generated by the server', async () => {
  const app = createApp({ authService: auth(), serveStatic: false });
  let r = await request(app);
  assert.equal(r.status, 200); assert.equal(r.body.google.configured, false);
  assert.equal(r.headers['Cache-Control'], 'no-store');
  r = await request(app, { url: '/api/health' });
  assert.deepEqual(r.body, { status: 'ok', googleConfigured: false });
  r = await request(app, { url: '/runtime-config.json' });
  assert.deepEqual(r.body, { authEnabled: true, apiBaseUrl: '', googleClientId: '', chatgpt: { enabled: false, mode: 'disabled', apiBaseUrl: '' } });
  r = await request(app, { method: 'POST', url: '/api/auth/challenge', origin: SERVER, body: {} });
  assert.equal(r.status, 503); assert.equal(r.body.error.code, 'not_configured');
});

test('allows exact CORS origins without third-party cookie access and rejects untrusted origins', async () => {
  const app = createApp({ authService: auth(), serveStatic: false });
  let r = await request(app, { origin: STATIC });
  assert.equal(r.headers['Access-Control-Allow-Origin'], STATIC);
  assert.equal(r.headers['Access-Control-Allow-Credentials'], undefined);
  r = await request(app, { origin: 'https://attacker.example' });
  assert.equal(r.status, 403); assert.equal(r.headers['Access-Control-Allow-Origin'], undefined);
  r = await request(app, { method: 'POST', url: '/api/auth/logout', body: {} });
  assert.equal(r.status, 403); assert.equal(r.body.error.code, 'origin_required');
  r = await request(app, { method: 'OPTIONS', origin: STATIC, headers: { 'access-control-request-method': 'POST', 'access-control-request-headers': 'content-type,authorization' } });
  assert.equal(r.status, 204); assert.equal(r.headers['Access-Control-Allow-Origin'], STATIC);
  r = await request(app, { method: 'OPTIONS', origin: STATIC, headers: { 'access-control-request-method': 'POST', 'access-control-request-headers': 'x-unknown' } });
  assert.equal(r.status, 403);
});

test('rejects malformed or oversized requests before provider verification and rate limits auth traffic', async () => {
  const app = createApp({ authService: auth(), serveStatic: false, maxBodyBytes: 100, challengeRateLimit: 4 });
  let r = await request(app, { method: 'POST', url: '/api/auth/google', origin: SERVER, body: '{' });
  assert.equal(r.status, 400); assert.equal(r.body.error.code, 'invalid_json');
  r = await request(app, { method: 'POST', url: '/api/auth/google', origin: SERVER, body: 'x'.repeat(101) });
  assert.equal(r.status, 413);
  r = await request(app, { method: 'POST', url: '/api/auth/google', origin: SERVER, body: {}, headers: { 'content-type': 'text/plain' } });
  assert.equal(r.status, 415);
  await request(app, { method: 'POST', url: '/api/auth/challenge', origin: SERVER, body: {} });
  r = await request(app, { method: 'POST', url: '/api/auth/challenge', origin: SERVER, body: {} });
  assert.equal(r.status, 429); assert.equal(r.headers['Retry-After'], '60');
});

test('does not serve repository source, environment files or arbitrary paths', async () => {
  const app = createApp({ authService: auth(), staticDirectory: new URL('../dist', import.meta.url).pathname });
  for (const url of ['/.env', '/.git/config', '/%2e%2e%2fserver/auth.js', '/server/auth.js']) {
    const r = await request(app, { url }); assert.equal(r.status, 404, url);
  }
});
